import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const origin = process.env.TEST_ORIGIN ?? 'http://127.0.0.1:3311';
const out = process.env.TEST_ARTIFACTS ?? 'verification-artifacts/vault';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH ?? process.env.PLAYWRIGHT_EXECUTABLE });
let checks = 0;
const check = (ok, message) => { assert.ok(ok, message); console.log(`PASS ${++checks}: ${message}`); };
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto(`${origin}/app`);
 await page.getByRole('combobox', { name: 'Your question' }).waitFor();
 const files = page.getByRole('button', {name: 'Files', exact: true});
 await files.click();
 await page.screenshot({ path: `${out}/files-menu-desktop.png` });
 await page.getByRole('button', { name: /Add from Wall System/ }).click();
 const dialog = page.getByRole('dialog', { name: 'Add from Wall System' });
 const ready = dialog.getByRole('checkbox', { name: /mutual-nda/ });
 await ready.waitFor();
 check(await dialog.getByRole('checkbox', { name: /supply-agreement/ }).isDisabled(), 'processing documents cannot be attached');
 check(await dialog.getByRole('checkbox', { name: /scanned-deed/ }).isDisabled(), 'unreadable documents cannot be attached');
 const search = dialog.getByRole('searchbox'); await search.focus();
 check(await search.evaluate(el => getComputedStyle(el.parentElement).outlineStyle !== 'none'), 'filename search has a visible keyboard focus indicator');
 await search.fill('mutual'); await page.waitForTimeout(450);
 await ready.waitFor(); check(await dialog.getByRole('checkbox').count() === 1, 'filename search narrows stored files');
 await search.fill(''); await page.waitForTimeout(400);
 await ready.click();
 await page.screenshot({ path: `${out}/vault-picker-desktop.png` });
 await dialog.getByRole('button', {name: 'Use 1 file', exact: true}).click();
 check(await page.getByRole('button', {name:'Remove mutual-nda.txt'}).isVisible(), 'chosen stored document appears as removable composer context');
 await page.waitForFunction(() => document.activeElement?.textContent === 'Files');
 check(await files.evaluate(el => el === document.activeElement), 'closing Vault restores focus to Files');
 await page.getByRole('button', {name: /sources — choose what is searched/}).click();
 check(await page.getByRole('switch', {name: /Wall System/}).getAttribute('aria-checked') === 'true', 'adding stored files selects the Vault source');
 // Unavailable sources (BSE) are listed inline in their group since 764323f, so their marks are in the same set.
 await page.waitForFunction(() => [...document.querySelectorAll('.source-picker-group .source-provider-logo')].length === 5 && [...document.querySelectorAll('.source-picker-group .source-provider-logo')].every(el => el.complete && el.naturalWidth > 0));
 check(await page.locator('.source-picker-group .source-provider-logo').evaluateAll(els => {
  const names = els.map(el => new URL(el.src).pathname.split('/').pop()).sort();
  return JSON.stringify(names) === JSON.stringify(['bse.png', 'ecourts.png', 'india-code.png', 'sebi.png', 'supreme-court.png']) && els.every(el => el.complete && el.naturalWidth > 0 && new URL(el.src).origin === location.origin);
 }), 'court, statute and regulator marks load locally with the expected source identities');
 await page.screenshot({ path: `${out}/official-sources-desktop.png` });
 const bseLogo = page.locator('.source-picker-unavailable-row img.source-provider-logo[src$="/source-logos/bse.png"]');
 await bseLogo.waitFor();
 await bseLogo.scrollIntoViewIfNeeded();
 await page.waitForFunction(() => { const el = document.querySelector('.source-picker-unavailable-row img.source-provider-logo[src$="/source-logos/bse.png"]'); return el?.complete && el.naturalWidth > 0; });
 check(await bseLogo.isVisible() && await bseLogo.evaluate(el => el.complete && el.naturalWidth > 0), 'the BSE mark stays with its unavailable source row');
 await page.screenshot({ path: `${out}/bse-source-unavailable.png` });
 await page.getByRole('button', {name:/Choose stored files/}).click();
 await ready.waitFor(); check(await ready.getAttribute('aria-checked') === 'true', 'Sources opens the same selection without duplicates');
 await page.keyboard.press('Escape');
 await page.waitForFunction(() => document.activeElement?.classList.contains('source-picker-trigger'));
 check(await page.locator('.source-picker-trigger').evaluate(el => el === document.activeElement), 'Escape returns focus to Sources');
 await page.getByRole('button', {name:'Remove mutual-nda.txt'}).click();
 check(await page.getByRole('button', {name:'Remove mutual-nda.txt'}).count() === 0, 'stored attachment can be removed');
 await page.setViewportSize({width:360,height:800});
 await files.click(); await page.getByRole('button', {name:/Add from Wall System/}).click();
 await ready.waitFor(); await page.screenshot({ path: `${out}/vault-picker-mobile.png` });
 const box = await dialog.boundingBox();
 check(box && box.x >= 0 && box.y >= 0 && box.x+box.width <= 360 && box.y+box.height <=800, 'Vault dialog fits a 360px screen');
 check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no horizontal overflow on mobile');
 await page.keyboard.press('Escape');
 await page.goto(`${origin}/app/vault`);
 await page.getByText('mutual-nda.txt', {exact:true}).waitFor();
 check(await page.getByRole('combobox', {name:'Document scope'}).isVisible(), 'Wall System lists named files with explicit scope');
 await page.screenshot({ path: `${out}/wall-system-mobile.png`, fullPage:true });
 check(errors.length === 0, `no browser runtime exceptions: ${errors.join('; ')}`);
 console.log(`${checks} Vault browser checks passed`);
} finally { await browser.close(); }
