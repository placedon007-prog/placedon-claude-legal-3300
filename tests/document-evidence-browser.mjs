/** Opt-in real gateway/worker/Postgres browser journey; run only on a disposable test workspace. */
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const origin = process.env.TEST_ORIGIN ?? 'http://127.0.0.1:3349';
const passcode = process.env.TEST_PASSCODE;
assert.ok(passcode, 'TEST_PASSCODE required; use an isolated synthetic-data workspace');
const out = process.env.TEST_ARTIFACTS ?? 'verification-artifacts/document-evidence';
await mkdir(out, { recursive: true });
const browser=await chromium.launch({headless:true, executablePath: process.env.CHROMIUM_PATH ?? process.env.PLAYWRIGHT_EXECUTABLE});
let n=0; const check=(ok,why)=>{assert.ok(ok,why);console.log(`PASS ${++n}: ${why}`)};
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/login');
 await page.getByLabel('Workspace passcode').fill(passcode);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 const input=page.getByRole('combobox',{name:'Your question'});
 await input.waitFor();
 await page.getByRole('button', { name: /sources? — choose what is searched/ }).click();
 const vault = page.getByRole('switch', { name: /Your documents/ });
 if (await vault.getAttribute('aria-checked') === 'true') await vault.click();
 await page.keyboard.press('Escape');
 const text='SYNTHETIC TEST AGREEMENT 📖\n\nTermination requires thirty days’ written notice.\n\nPayment is due within fifteen days.\n\nNo real client data. '+Date.now();
 await page.locator('input[type=file]').setInputFiles({name:`synthetic-${Date.now()}.txt`,mimeType:'text/plain',buffer:Buffer.from(text)});
 await page.getByText(/· ready to read ·/).waitFor({timeout:30000});
 check(true,'browser upload extracted text and real worker ingested it');
 const enable=page.getByRole('button',{name:'Turn on Your documents',exact:true});
 await input.fill('What does the document say about termination?');
 check(await page.getByRole('button',{name:'Send',exact:true}).isDisabled(),'attachment with disabled document source cannot send');
 await enable.click();
 check(await page.getByRole('button',{name:'Send',exact:true}).isEnabled(),'enabling document sources enables a valid attached question');
 await input.press('Enter');
 await page.getByRole('heading',{name:'Document excerpts matching your question',exact:true}).waitFor({timeout:30000});
 const quote=page.getByRole('article',{name:'Document research result'}).locator('blockquote').first();
 check(await quote.innerText()==='Termination requires thirty days’ written notice.','answer contains exact selected document quote');
 const url=page.url(); check(url.includes('?c='),'conversation identity present');
 const summary=page.getByText('Excerpt details',{exact:true}).first();
 await summary.focus(); await page.keyboard.press('Enter');
 check(await page.getByText('Characters ',{exact:false}).first().isVisible(),'keyboard reveals provenance');
 check((await page.getByText('SHA-256',{exact:false}).first().innerText()).includes('SHA-256'),'content hash visible');
 check(await page.getByRole('button',{name:/Create draft from/}).count()===0,'extract does not offer legal draft action');
 await summary.click();
 await page.screenshot({path:out+'/desktop.png',fullPage:true});
 await page.reload(); await page.getByRole('heading',{name:'Document excerpts matching your question',exact:true}).waitFor();
 check(await page.locator('blockquote').first().innerText()==='Termination requires thirty days’ written notice.','reopen preserves evidence');
 await page.setViewportSize({width:390,height:844});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile view has no horizontal overflow');
 await page.screenshot({path:out+'/mobile.png',fullPage:true});
 check(errors.length===0,`no browser runtime errors (${errors.length})`);
 console.log('Saved test conversation '+url);
} finally {await browser.close()}
