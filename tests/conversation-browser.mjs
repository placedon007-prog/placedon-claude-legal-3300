import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const origin = process.env.TEST_ORIGIN ?? "http://localhost:3311";
const artifacts = process.env.TEST_ARTIFACTS ?? "verification-artifacts/conversation";
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH ?? process.env.PLAYWRIGHT_EXECUTABLE });
const errors = [];
let checks = 0;
const check = (ok, message) => { assert.ok(ok, message); checks++; console.log(`PASS ${checks}: ${message}`); };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, reducedMotion: "reduce" });
  await context.tracing.start({ screenshots: true, snapshots: true });
  const page = await context.newPage();
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${origin}/app`);
  await page.getByRole("combobox", { name: "Your question" }).waitFor();
  await page.getByText("Demo · recorded examples", { exact: false }).waitFor();
  check(await page.getByText("Unfiled workspace", { exact: true }).count() === 1, "new conversation does not imply a private personal workspace");
  const input = page.getByRole("combobox", { name: "Your question" });
  check(await input.getAttribute("maxlength") === "8000", "prompt supports 8000 characters");
  await page.screenshot({ path: `${artifacts}/conversation-welcome-desktop.png`, fullPage: true });
  await page.getByRole("button", { name: "2 sources — choose what is searched" }).click();
  check(await page.getByText(/Unsent choices are remembered in this browser/, { exact: false }).count() === 1, "source picker explains local persistence for unsent choices");
  const law = page.getByRole("switch", { name: /Companies Act.*held corpus/ });
  const documents = page.getByRole("switch", { name: /Your documents.*vault/ });
  await law.click();
  await documents.focus();
  await page.keyboard.press("Space");
  check(await documents.getAttribute("aria-checked") === "true" && await documents.getAttribute("aria-disabled") === "true", "last source stays selected and explains the constraint");
  check(await page.locator(".source-picker-trigger .source-india-flag").count() === 0, "source chip uses a document icon when only the vault is selected");
  await law.focus();
  await page.keyboard.press("Space");
  check(await law.getAttribute("aria-checked") === "true", "source rows support keyboard selection");
  check(await page.locator(".source-picker-trigger .source-india-flag").count() === 1, "source chip identifies the selected Indian jurisdiction");
  await law.click();
  await law.click();
  check(await page.locator(".source-picker").getAttribute("data-motion") === "pointer" && await page.locator(".source-picker").evaluate((el) => getComputedStyle(el.querySelector(".source-picker-switch > span")).transitionDuration) === "0s", "system reduced motion disables switch movement after pointer selection");
  await page.screenshot({ path: `${artifacts}/source-picker-desktop.png`, fullPage: true });
  // Unavailable sources are listed inline in their group (no separate "Other sources" fold since 764323f).
  await page.locator(".source-picker-unavailable-row", { hasText: "BSE (Bombay Stock Exchange) announcements" }).scrollIntoViewIfNeeded();
  check(await page.locator(".source-picker-unavailable-row").count() > 0 && await page.locator(".source-picker-unavailable-row [role=switch]").count() === 0, "unavailable sources show reasons without selection controls");
  check(await page.getByText("robots: https://www.bseindia.com BLOCKED HTTP 403", { exact: false }).isVisible(), "unavailable source reason remains inspectable");
  await page.keyboard.press("Escape");
  check(await page.getByRole("button", { name: "2 sources — choose what is searched" }).evaluate((el) => el === document.activeElement), "closing the picker restores focus to the source chip");
  await input.fill("What are the annual general meeting requirements under Section 96?");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.getByRole("heading", { name: "Sources", exact: true }).waitFor();
  const answerPath = page.locator(".answer-path");
  await answerPath.locator(":scope > summary").click();
  check(await answerPath.locator("ol > li").count() === 5, "answer trace exposes five inspectable workflow checkpoints");
  const searchStage = answerPath.locator("ol > li").nth(2);
  await searchStage.locator("summary").click();
  check(await searchStage.getByText(/Companies Act 2013: searched/).count() === 1, "search checkpoint explains the gateway's recorded source outcome in readable labels");
  const scopeStage = answerPath.locator("ol > li").nth(1);
  await scopeStage.locator("summary").click();
  check(await scopeStage.getByText(/Matter: unfiled workspace/).count() === 1, "scope checkpoint uses the current request's recorded unfiled state");
  const evidenceStage = answerPath.locator("ol > li").nth(3);
  await evidenceStage.locator("summary").click();
  const inspectCitation = evidenceStage.getByRole("button", { name: "Open Section 96" });
  check(await inspectCitation.count() === 1, "evidence checkpoint offers a direct path to its verified source");
  await inspectCitation.click();
  await page.getByRole("complementary", { name: "Source", exact: true }).waitFor();
  await page.getByRole("button", { name: "Close source", exact: true }).click();
  await answerPath.locator(":scope > summary").click();
  check(await page.getByRole("complementary", { name: "Source", exact: true }).count() === 0, "source panel never opens without explicit choice");
  const url = page.url();
  check(url.includes("?c="), "accepted conversation has a stable URL");
  await page.getByRole("link", { name: "New question", exact: true }).filter({ visible: true }).click();
  await page.getByRole("heading", { level: 1, name: "New conversation" }).waitFor();
  check(await page.getByRole("heading", { level: 2, name: /annual general/ }).count() === 0, "sidebar New clears the just-created workspace without a reload first");
  await input.fill("When must a company hold its annual general meeting?");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.getByRole("heading", { name: "Sources", exact: true }).waitFor();
  check(page.url() !== url, "sidebar New creates a distinct conversation");
  await page.goto(url);
  await page.reload();
  await page.getByRole("heading", { name: "Sources", exact: true }).waitFor();
  check(await page.getByRole("heading", { level: 2, name: /annual general/ }).count() === 1, "reload preserves one turn without duplicates");
  await page.locator(".answer-path > summary").click();
  const reloadedScope = page.locator(".answer-path ol > li").nth(1);
  check((await reloadedScope.locator("summary").innerText()).includes("Partly recorded"), "reloaded trace does not imply omitted matter metadata was preserved");
  await reloadedScope.locator("summary").click();
  check(await reloadedScope.getByText(/Matter: not recorded on this saved turn/).count() === 1, "reloaded trace marks missing matter metadata explicitly");
  await page.getByRole("link", { name: "New", exact: true }).click();
  await page.getByRole("combobox", { name: "Your question" }).fill("When must a company hold its first annual general meeting?");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.getByRole("heading", { name: "Sources", exact: true }).waitFor();
  await page.getByRole("link", { name: "What are the annual general meeting requirements under Section 96?", exact: true }).click();
  await page.getByRole("heading", { level: 2, name: "What are the annual general meeting requirements under Section 96?", exact: true }).waitFor();
  check(await page.getByRole("heading", { level: 2, name: /When must a company/ }).count() === 0, "sidebar navigation switches to the server-loaded conversation without stale turns");
  await page.getByRole("button", { name: /Source 1, Section 96/ }).first().click();
  await page.getByRole("complementary", { name: "Source", exact: true }).waitFor();
  await page.getByText("Re-read just now: the quote byte-matches the held text.").first().waitFor();
  await page.screenshot({ path: `${artifacts}/conversation-source-desktop.png`, fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "desktop has no horizontal overflow");
  await page.getByRole("button", { name: "Close source", exact: true }).click();
  await page.setViewportSize({ width: 1024, height: 900 });
  await page.getByRole("button", { name: /Source 1, Section 96/ }).first().click();
  await page.getByRole("dialog").waitFor();
  check(await page.getByRole("complementary", { name: "Source", exact: true }).count() === 0, "1024 uses an overlay and preserves reading width");
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 360, height: 800 });
  await page.screenshot({ path: `${artifacts}/conversation-mobile.png`, fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "360px has no horizontal overflow");
  await page.getByRole("button", { name: "2 sources — choose what is searched" }).click();
  await page.screenshot({ path: `${artifacts}/source-picker-mobile.png`, fullPage: true });
  const pickerBox = await page.locator(".source-picker").boundingBox();
  check(pickerBox && pickerBox.x >= 0 && pickerBox.x + pickerBox.width <= 360 && pickerBox.y >= 0 && pickerBox.y + pickerBox.height <= 800, "source picker fits the 360px viewport");
  await page.getByRole("switch", { name: /SEBI \(Securities/ }).scrollIntoViewIfNeeded();
  check(await page.getByRole("switch", { name: /SEBI \(Securities/ }).isVisible(), "mobile source catalog scrolls to its final available option");
  await page.getByRole("button", { name: "Close source picker", exact: true }).click();
  await page.getByRole("button", { name: /Source 1, Section 96/ }).first().click();
  await page.getByRole("dialog").waitFor();
  await page.getByText("Re-read just now: the quote byte-matches the held text.").first().waitFor();
  await page.screenshot({ path: `${artifacts}/conversation-source-mobile.png`, fullPage: true });
  await page.keyboard.press("Escape");
  check(await page.getByRole("dialog").count() === 0, "Escape closes the source sheet");

  // Lose an acknowledgment after the server has accepted the request. Retry must
  // recover exactly that request, and the composer must prevent a competing write.
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto(`${origin}/app`);
  const interruptedQuestion = "What meeting records must the company keep for its annual general meeting?";
  const writes = [];
  let dropped = false;
  const interrupt = async (route) => {
    const request = route.request();
    if (request.method() !== "POST" || !request.headers()["next-action"] || !request.postData()?.includes(interruptedQuestion)) return route.continue();
    writes.push(request.postData());
    if (dropped) return route.continue();
    dropped = true;
    const response = await route.fetch();
    check(response.ok(), "server accepted the response before the connection was lost");
    await response.body();
    await route.abort("connectionreset");
  };
  await page.route("**/app*", interrupt);
  await input.fill(interruptedQuestion);
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await page.getByRole("button", { name: "Try again", exact: true }).waitFor();
  await input.fill("This second question must wait for recovery.");
  check(await page.locator('button[type="submit"]').isDisabled(), "uncertain first request blocks competing writes");
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await page.getByRole("heading", { name: "Sources", exact: true }).waitFor();
  check(writes.length === 2 && writes[0] === writes[1], "retry sends exactly the same request ID and payload");
  await page.unroute("**/app*", interrupt);
  await page.reload();
  await page.getByRole("heading", { name: "Sources", exact: true }).waitFor();
  check(await page.getByRole("heading", { level: 2, name: interruptedQuestion, exact: true }).count() === 1, "lost acknowledgment recovery produces one persisted turn");

  // Hold a completed action while navigating with a sidebar Next Link. Its late
  // completion must not replace the newly opened conversation's URL or content.
  await page.goto(`${origin}/app`);
  const lateQuestion = "Explain the annual general meeting time limits for this late response test.";
  let release;
  const held = new Promise((resolve) => { release = resolve; });
  let announce;
  const captured = new Promise((resolve) => { announce = resolve; });
  let completed;
  const fulfilled = new Promise((resolve) => { completed = resolve; });
  const delay = async (route) => {
    const request = route.request();
    if (request.method() !== "POST" || !request.headers()["next-action"] || !request.postData()?.includes(lateQuestion)) return route.continue();
    const response = await route.fetch();
    announce();
    await held;
    await route.fulfill({ response });
    completed();
  };
  await page.route("**/app*", delay);
  await input.fill(lateQuestion);
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await captured;
  await page.getByRole("link", { name: "What are the annual general meeting requirements under Section 96?", exact: true }).click();
  await page.getByRole("heading", { level: 2, name: "What are the annual general meeting requirements under Section 96?", exact: true }).waitFor();
  release();
  await fulfilled;
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  check(page.url() === url, "a late send cannot overwrite the conversation opened through client navigation");
  check(await page.getByRole("heading", { level: 2, name: lateQuestion, exact: true }).count() === 0, "a late response cannot enter another thread");
  await page.unroute("**/app*", delay);
  check(errors.length === 0, `no browser runtime errors: ${errors.join("; ")}`);
  await context.tracing.stop({ path: `${artifacts}/conversation-trace.zip` });
  await writeFile(`${artifacts}/results.json`, JSON.stringify({ status: "passed", checks, errors, origin }, null, 2));
  console.log(JSON.stringify({ status: "passed", checks, artifacts }));
} finally { await browser.close(); }
